#!/usr/bin/env python3
"""설계처럼 되돌리기 어려운 자리에서 «상위 모델»을 권하는 글을 찍는다 — 모델을 정하지 않는다."""
import sys

낮은 = ("haiku", "sonnet")
까닭 = {
    "설계": "설계는 나중에 바꾸기 어려운 결정(기능 사이 연결 · 데이터 · 결제 · 로그인)이 많아",
    "가져오기": "가져오기는 코드를 읽고 설계 칸을 채우는 일이라 잘못 읽으면 뒤 단계가 모두 틀어져",
}
모델 = (sys.argv[1] if len(sys.argv) > 1 else "").strip().lower()
때 = sys.argv[2] if len(sys.argv) > 2 else "설계"
권함 = ("«" + 까닭.get(때, 까닭["설계"]) + ", 상위 모델로 바꿔서 진행하시길 권합니다. "
        "모델 고르는 곳(/model)에서 바꾸실 수 있고, 지금 모델로 계속하셔도 됩니다.»")
끝 = " 한 번만 말하고, 사용자가 그대로 하자고 하시면 다시 권하지 마십시오. 막지 않습니다."
if not 모델:
    print("  [모델] 상위 모델 권함: 지금 모델이 상위 모델이 아니면(이름에 Haiku · Sonnet 이 든 모델) 사용자에게 한 줄로 권하십시오: " + 권함 + 끝)
elif any(x in 모델 for x in 낮은):
    print("  [모델] 상위 모델 권함: 지금 모델(" + 모델[:60] + ")은 상위 모델이 아닙니다. 사용자에게 한 줄로 권하십시오: " + 권함 + 끝)
